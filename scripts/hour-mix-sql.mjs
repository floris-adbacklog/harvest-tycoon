// Writes supabase/hour-mix.sql (29 Oct 2026, the owner: "bij events komen er bij hogere league 'nieuwe' events bij, maar de vorige
// kunnen ook nog gehaald worden", option 2): a higher world's league draws its hourly goal half of the time from its own world's pool,
// as now, and half of the time from the worlds before it (public/event-goals.js EVENT_HOUR_MIX): a village league's other half from the
// farm, a harbour league's a quarter from the village and a quarter from the farm, each at its top league's numbers.
// Only harvest_event_pick changes, from the body read live on 29 Oct 2026 (supabase/harbour-leagues.sql made it). A farm league's goal
// stays exactly as it would have been; an event already made keeps its goals.
// Run: node scripts/hour-mix-sql.mjs. Never edit the SQL file by hand. Not at hh:00-hh:04 UTC, when harvest_event_schedule makes the
// next events (an event runs every hour, so there is no break to wait for; a running event never reads the pick again).
import {writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {EVENT_LEAGUES} from '../game/farm-state.js';
import {hourGoalSources} from '../public/event-goals.js';
import {HOUR_PICK_BODY_MIX} from './event-goals-sql.mjs';
import {PICK_BODY as LIVE_PICK,NEW_MD5 as HARBOUR_MD5} from './harbour-leagues-sql.mjs';

const md5=text=>createHash('md5').update(text).digest('hex');
export const LIVE_MD5='662d444e40f2d89fff524fbd551f023f';
if(md5(LIVE_PICK)!==LIVE_MD5||HARBOUR_MD5['harvest_event_pick(bigint)']!==LIVE_MD5)throw Error('harvest_event_pick(bigint): the body from its generator is not the live one');
export const PICK_BODY=HOUR_PICK_BODY_MIX;
export const NEW_MD5=md5(PICK_BODY);
const FARM=EVENT_LEAGUES.filter(l=>l.world===1).length;
// What each league's goal may be now: its own pool's and the older worlds' top pools' (the after-check).
export const ALLOWED=Object.freeze(EVENT_LEAGUES.map(l=>[...new Set(hourGoalSources(l.index).flatMap(s=>s.pool.flat().map(g=>g.stat)))]));

const HEAD='public.harvest_event_pick(n bigint)\n returns jsonb language plpgsql stable set search_path to \'\'';
const SQL=`-- Generated by scripts/hour-mix-sql.mjs. Do not edit by hand.
-- Older worlds' goals in the higher leagues (29 Oct 2026, the owner: option 2): a village league's hourly goal comes half of the time
-- from the farm, a harbour league's a quarter of the time from the village and a quarter from the farm, at the numbers of that world's
-- top league; the rest as now. Only harvest_event_pick changes. The farm's leagues draw exactly as before.
-- Run it any time but hh:00-hh:04 UTC. Save the harvest_event_pick definition first (no PITR). One transaction: any failed check rolls
-- all of it back. Running it twice changes nothing.
begin;
set local lock_timeout='5s';
do $guard$ declare have text; begin
 if extract(minute from now())<5 then raise exception 'not at hh:00-hh:04 UTC: harvest_event_schedule makes the next events then'; end if;
 select md5(prosrc) into have from pg_proc where oid=to_regprocedure('public.harvest_event_pick(bigint)');
 if have is null or have not in ('${LIVE_MD5}','${NEW_MD5}') then raise exception 'public.harvest_event_pick(bigint) is not the one this file expects (md5 %); read the live definition first', have; end if;
end $guard$;

-- The next 48 hours as the pick makes them now, to compare with after.
create temp table hour_mix_before on commit drop as
 select h as n, public.harvest_event_pick(h) as t from generate_series(floor(extract(epoch from now())/3600)::bigint+3,floor(extract(epoch from now())/3600)::bigint+50) h;

create or replace function ${HEAD} as $function$${PICK_BODY}$function$;

-- After-check, in the same transaction.
do $after$ declare allowed jsonb:='${JSON.stringify(ALLOWED)}'; b record; t jsonb; lg int; o jsonb; older int:=0; begin
 if (select md5(prosrc) from pg_proc where oid=to_regprocedure('public.harvest_event_pick(bigint)')) is distinct from '${NEW_MD5}' then raise exception 'public.harvest_event_pick(bigint) did not come out as generated'; end if;
 if exists(select 1 from pg_proc p where p.oid=to_regprocedure('public.harvest_event_pick(bigint)')
    and (p.prosecdef or p.provolatile<>'s' or p.proconfig is distinct from array['search_path=""'] or p.proacl::text is distinct from '{postgres=X/postgres,service_role=X/postgres}'))
  then raise exception 'the function header or grant changed'; end if;
 for b in select * from hour_mix_before loop
  t:=public.harvest_event_pick(b.n);
  if jsonb_array_length(t->'leagues')<>${EVENT_LEAGUES.length} then raise exception 'hour %: not % leagues', b.n, ${EVENT_LEAGUES.length}; end if;
  -- The farm's leagues draw exactly as before.
  if (select jsonb_agg(x order by i) from jsonb_array_elements(t->'leagues') with ordinality e(x,i) where i<=${FARM}) is distinct from (select jsonb_agg(x order by i) from jsonb_array_elements(b.t->'leagues') with ordinality e(x,i) where i<=${FARM})
   then raise exception 'hour %: a farm league''s goal changed', b.n; end if;
  for lg in 0..${EVENT_LEAGUES.length-1} loop
   o:=t->'leagues'->lg->'objectives';
   if jsonb_array_length(o)<>1 or not allowed->lg ? (o->0->>'stat') or (o->0->>'target')::int<1 or coalesce(t->'leagues'->lg->>'title','')='' then raise exception 'hour % league %: % is not one of its goals', b.n, lg, o; end if;
   if lg>=${FARM} and o is distinct from b.t->'leagues'->lg->'objectives' then older:=older+1; end if;
  end loop;
 end loop;
 -- In 48 hours some of the ${EVENT_LEAGUES.length-FARM} higher leagues' goals come from an older world (about half of them do).
 if older=0 then raise exception 'no higher league drew another goal in 48 hours'; end if;
end $after$;
commit;
`;
export function hourMixSql(){return SQL;}
if(import.meta.url===`file://${process.argv[1]}`){
 writeFileSync(new URL('../supabase/hour-mix.sql',import.meta.url),SQL);
 console.log('supabase/hour-mix.sql',SQL.length,'characters');
 console.log('harvest_event_pick(bigint)',LIVE_MD5,'->',NEW_MD5);
}
