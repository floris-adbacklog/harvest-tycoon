// Writes supabase/tractor-fertilize-events.sql (25 Oct 2026, a player via the owner: "besmeten werkt niet meer bij events").
// Since 24 Oct 2026 the tractor's Fertilize job is the only way to fertilize a field (the Windmill's by hand is gone), and it is
// saved as the action 'tractor'. harvest_event_progress counted the "Fertilize fields" goal only for the action 'fertilize', so a
// tractor fertilize only moved the farmer's baseline and the goal stayed at 0. Now the goal counts for both: 'fertilize' (an older
// page, by hand) and 'tractor' (only its Fertilize job raises stats.fertilized; the diamond work is no event action at all).
// Read live on 25 Oct 2026: harvest_event_progress() is the one supabase/league-at-join.sql made (md5 below). Read it again right
// before running this file; if it differs, paste it here and regenerate.
// Run: node scripts/tractor-fertilize-events-sql.mjs. Never edit the file by hand. Any time: no hand-out or settle is touched.
import {writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {PROGRESS_BODY as LIVE_PROGRESS,NEW_MD5 as LEAGUE_AT_JOIN_MD5} from './league-at-join-sql.mjs';

const md5=text=>createHash('md5').update(text).digest('hex');
export const LIVE_MD5='4eef8c3039a4316ad5b6a45a4a897b69';
if(md5(LIVE_PROGRESS)!==LIVE_MD5||LEAGUE_AT_JOIN_MD5['harvest_event_progress()']!==LIVE_MD5)throw Error('harvest_event_progress(): the body from its generator is not the live one');

export const OLD_LINE=`(stat='fertilized' and action='fertilize')`;
export const NEW_LINE=`(stat='fertilized' and action in ('fertilize','tractor'))`;
if(LIVE_PROGRESS.split(OLD_LINE).length!==2)throw Error('The live body changed: the fertilized line');
export const PROGRESS_BODY=LIVE_PROGRESS.replace(OLD_LINE,()=>NEW_LINE);
export const NEW_MD5=md5(PROGRESS_BODY);

const HEAD='public.harvest_event_progress()\n returns trigger language plpgsql set search_path to \'\'';
const SQL=`-- Generated by scripts/tractor-fertilize-events-sql.mjs. Do not edit by hand.
-- "Fertilize fields" in events counts the tractor's Fertilize job again (25 Oct 2026): since 24 Oct 2026 fertilizing goes only through
-- the tractor (saved as the action 'tractor'), and the goal counted only the action 'fertilize'. One line of harvest_event_progress.
-- Run it any time (no hand-out or settle is touched). Save the harvest_event_progress definition first (no PITR). One transaction:
-- any failed check rolls all of it back. Running it twice changes nothing.
begin;
set local lock_timeout='5s';
do $guard$ declare have text; begin
 select md5(prosrc) into have from pg_proc where oid=to_regprocedure('public.harvest_event_progress()');
 if have is null or have not in ('${LIVE_MD5}','${NEW_MD5}') then raise exception 'public.harvest_event_progress() is not the one this file expects (md5 %); read the live definition first', have; end if;
end $guard$;

create or replace function ${HEAD} as $function$${PROGRESS_BODY}$function$;

-- After-check, in the same transaction.
do $after$ begin
 if (select md5(prosrc) from pg_proc where oid=to_regprocedure('public.harvest_event_progress()')) is distinct from '${NEW_MD5}' then raise exception 'public.harvest_event_progress() did not come out as generated'; end if;
 -- The header and grants as live: not security definer, volatile, search_path '', only postgres and service_role.
 if exists(select 1 from pg_proc p where p.oid=to_regprocedure('public.harvest_event_progress()')
    and (p.prosecdef or p.provolatile<>'v' or p.proconfig is distinct from array['search_path=""']
     or p.proacl::text is distinct from '{postgres=X/postgres,service_role=X/postgres}'))
  then raise exception 'the function header or grant changed'; end if;
 -- Still the trigger on player_farms.
 if not exists(select 1 from pg_trigger t where t.tgrelid='public.player_farms'::regclass and not t.tgisinternal and t.tgenabled<>'D'
    and t.tgfoid='public.harvest_event_progress()'::regprocedure) then raise exception 'harvest_event_progress is no longer a trigger on player_farms'; end if;
end $after$;
commit;
`;
export function tractorFertilizeEventsSql(){return SQL;}
if(import.meta.url===`file://${process.argv[1]}`){
 writeFileSync(new URL('../supabase/tractor-fertilize-events.sql',import.meta.url),SQL);
 console.log('supabase/tractor-fertilize-events.sql',SQL.length,'characters');
 console.log('harvest_event_progress()',LIVE_MD5,'->',NEW_MD5);
}
