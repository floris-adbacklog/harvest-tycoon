// Writes supabase/family-share-24h.sql (20 Oct 2026). Share in chat once a day: the owner changed the rule the evening it went live
// ("once per 24 hours instead of once an hour"). Only the function changes: harvest_family_share checks families.shared_at against a
// day (FAMILY_SHARE_GAP_MS, game/farm-state.js, 86400000) instead of an hour, and its refusal says "less than a day ago". Everything
// else is the body that is live (scripts/family-share-sql.mjs SHARE_BODY, md5 ac05b2645eb31dde092059a957255205), word for word.
// - The guard: the live body is the hour one this file was made from, or already this day one (a second run changes nothing).
// - Same header as before (plpgsql, search_path '', not security definer) and the same grant: farm-api only (service_role).
// - The after-check, in the same transaction: the body as generated, the header and the grant.
// Run: node scripts/family-share-24h-sql.mjs. Never edit the file by hand.
import {writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {FAMILY_SHARE_GAP_MS} from '../game/farm-state.js';
import {SHARE_BODY,SHARE_MD5,FIRST_GAP_MS} from './family-share-sql.mjs';

const md5=text=>createHash('md5').update(text).digest('hex');
// Each part of the hour body that changes, and what it becomes; each must be in it exactly once.
export const DAY_CHANGES=Object.freeze([
 ["-- Once an hour per family: the family's row is locked, so two taps at once give one card.","-- Once a day per family (the owner, 20 Oct 2026; it was once an hour): the family's row is locked, so two taps at once give one card."],
 [`f.shared_at>now_ms-${FIRST_GAP_MS} then`,`f.shared_at>now_ms-${FAMILY_SHARE_GAP_MS} then`],
 ["'Your family was shared in the chat less than an hour ago.'","'Your family was shared in the chat less than a day ago.'"]
]);
export const DAY_BODY=DAY_CHANGES.reduce((body,[from,to])=>{
 if(body.split(from).length!==2)throw new Error(`family-share-24h: not exactly once in the live body: ${from}`);
 return body.replace(from,to);
},SHARE_BODY);
export const DAY_MD5=md5(DAY_BODY);
export const HOUR_MD5=SHARE_MD5;
const SIG='harvest_family_share(uuid,uuid,integer)';

const SQL=`-- Generated by scripts/family-share-24h-sql.mjs. Do not edit by hand.
-- Share in chat once a day (20 Oct 2026, the owner: once per 24 hours instead of once an hour). Replaces harvest_family_share with the
-- same body and a day: families.shared_at must be ${FAMILY_SHARE_GAP_MS} ms (24 hours) ago, and the refusal says "less than a day ago".
-- Nothing else changes: no table, no column, no player data.
-- Release: run this first (supabase/family-share.sql is live already), then deploy farm-api, then push the site. One transaction: a
-- failed check rolls it all back. Running it twice changes nothing.
begin;
set local lock_timeout='5s';
do $guard$
declare have text;
begin
 select md5(pr.prosrc) into have from pg_proc pr where pr.oid=to_regprocedure('public.${SIG}');
 if have is null then raise exception 'family-share-24h.sql: public.harvest_family_share is missing; run supabase/family-share.sql first'; end if;
 if have not in ('${HOUR_MD5}','${DAY_MD5}') then
  raise exception 'family-share-24h.sql: public.harvest_family_share is not the one this file expects (md5 %); read the live definition first', have; end if;
end $guard$;

create or replace function public.harvest_family_share(p_player uuid, p_family uuid, p_level integer)
 returns jsonb language plpgsql set search_path to '' as $function$${DAY_BODY}$function$;
revoke all on function public.${SIG} from public, anon, authenticated;
grant execute on function public.${SIG} to service_role;

-- After-check, in the same transaction.
do $after$
begin
 if (select md5(pr.prosrc) from pg_proc pr where pr.oid=to_regprocedure('public.${SIG}')) is distinct from '${DAY_MD5}' then
  raise exception 'family-share-24h.sql: harvest_family_share did not come out as generated'; end if;
 if exists(select 1 from pg_proc pr where pr.oid=to_regprocedure('public.${SIG}') and (pr.prosecdef or pr.proconfig is distinct from array['search_path=""']
   or pr.proacl::text is distinct from '{postgres=X/postgres,service_role=X/postgres}')) then raise exception 'family-share-24h.sql: harvest_family_share header or grant'; end if;
end $after$;
commit;

-- Check (read-only), after running this file: '${DAY_MD5}' and true.
-- select md5(prosrc), prosrc like '%now_ms-${FAMILY_SHARE_GAP_MS} then%' from pg_proc where oid=to_regprocedure('public.${SIG}');
`;
export function familyShareDaySql(){return SQL;}
if(import.meta.url===`file://${process.argv[1]}`){
 writeFileSync(new URL('../supabase/family-share-24h.sql',import.meta.url),SQL);
 console.log('supabase/family-share-24h.sql',SQL.length,'characters, harvest_family_share md5',DAY_MD5);
}
