// Writes public/lucide-icons.js: Lucide's createIcons() with only the line icons the game uses, instead of the whole library (1,939
// icons, 400 KB) in public/vendor/lucide.min.js. An icon counts as used when its name appears in quotes anywhere in the game's own
// code (data-lucide="coins", a name picked in a template like 'check', an icon field like icon:'droplets'), so names chosen at run
// time are included too; a few extra names that happen to match cost next to nothing. Run by build-static.mjs on every deploy and
// by hand after adding an icon (tests/lucide-icons.test.mjs checks that every data-lucide name in the code is in the file).
import {readFileSync,readdirSync,writeFileSync,existsSync} from 'node:fs';
import vm from 'node:vm';

const root=new URL('../',import.meta.url);
const read=path=>readFileSync(new URL(path,root),'utf8');
const library=read('public/vendor/lucide.min.js');
const context={};context.globalThis=context;vm.createContext(context);vm.runInContext(library,context);
const all=context.lucide.icons;
const pascal=name=>name.replace(/^([A-Z])|[\s-_]+(\w)/g,(m,first,next)=>next?next.toUpperCase():first.toLowerCase()).replace(/^./,c=>c.toUpperCase());

const sources=[];
for(const dir of ['public','src','game']){
 const path=new URL(`${dir}/`,root);if(!existsSync(path))continue;
 for(const file of readdirSync(path))if(/\.(js|html)$/.test(file)&&file!=='lucide-icons.js')sources.push(readFileSync(new URL(file,path),'utf8'));
}
const names=new Set();
for(const text of sources)for(const m of text.matchAll(/["'`]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)["'`]/g))if(all[pascal(m[1])])names.add(m[1]);
const icons=Object.fromEntries([...names].sort().map(name=>[pascal(name),all[pascal(name)]]));

const license=library.slice(0,library.indexOf('*/')+2);
const code=`${license}
// Generated by scripts/build-lucide-subset.mjs: only the ${Object.keys(icons).length} icons the game uses. Same createIcons() as Lucide's.
(function(){
const defaults={xmlns:"http://www.w3.org/2000/svg",width:24,height:24,viewBox:"0 0 24 24",fill:"none",stroke:"currentColor","stroke-width":2,"stroke-linecap":"round","stroke-linejoin":"round"};
const icons=${JSON.stringify(icons)};
const element=([tag,attrs,children])=>{const el=document.createElementNS("http://www.w3.org/2000/svg",tag);Object.keys(attrs).forEach(k=>el.setAttribute(k,String(attrs[k])));children?.length&&children.forEach(c=>el.appendChild(element(c)));return el;};
const pascal=name=>name.replace(/^([A-Z])|[\\s-_]+(\\w)/g,(m,first,next)=>next?next.toUpperCase():first.toLowerCase()).replace(/^./,c=>c.toUpperCase());
const labelled=attrs=>{for(const k in attrs)if(k.startsWith("aria-")||k==="role"||k==="title")return true;return false;};
const classes=value=>typeof value==="string"?value.split(" "):[];
function replace(el,attrs){
 const name=el.getAttribute("data-lucide");if(name==null)return;
 const icon=icons[pascal(name)];if(!icon)return console.warn(\`\${el.outerHTML} icon name was not found in the provided icons object.\`);
 const own=Array.from(el.attributes).reduce((all,a)=>(all[a.name]=a.value,all),{});
 const merged={...defaults,"data-lucide":name,...(labelled(own)?{}:{"aria-hidden":"true"}),...attrs,...own};
 const cls=["lucide",\`lucide-\${name}\`,...classes(own.class),...classes(attrs.class)].filter((c,i,list)=>c&&c.trim()!==""&&list.indexOf(c)===i).join(" ").trim();
 if(cls)merged.class=cls;
 el.parentNode?.replaceChild(element(["svg",merged,icon]),el);
}
function createIcons({attrs={},root=document}={}){Array.from(root.querySelectorAll("[data-lucide]")).forEach(el=>replace(el,attrs));}
window.lucide={createIcons,icons};
})();
`;
writeFileSync(new URL('public/lucide-icons.js',root),code);
console.log(`lucide-icons.js: ${Object.keys(icons).length} icons, ${(code.length/1024).toFixed(1)} KB`);
